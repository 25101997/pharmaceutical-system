async function tableExists(conn, name) {
  const r = await conn.execute('SELECT COUNT(*) AS CNT FROM USER_TABLES WHERE TABLE_NAME = :name', { name });
  return Number(r.rows[0].CNT) > 0;
}

async function ensureSchema() {
  const conn = await getConnection();
  try {
    const tableNames = ['ROLES','FARMACIAS','USUARIOS','MEDICAMENTOS','INVENTARIO','TRASLADOS','TRASLADO_DETALLE','ACTIVOS','MOVIMIENTOS_CAJA','EMPLEADOS','PLANILLAS','CLIENTES','PEDIDOS','PEDIDO_DETALLE','ENTREGAS'];
    for (let i = 0; i < ddl.length; i++) {
      if (!(await tableExists(conn, tableNames[i]))) await conn.execute(ddl[i]);
    }

    await conn.execute(`MERGE INTO ROLES r USING (SELECT 'ADMINISTRADOR' NOMBRE FROM DUAL) s ON (r.NOMBRE=s.NOMBRE)
      WHEN NOT MATCHED THEN INSERT (NOMBRE, DESCRIPCION) VALUES ('ADMINISTRADOR','Acceso total')`);
    await conn.execute(`MERGE INTO ROLES r USING (SELECT 'OPERADOR' NOMBRE FROM DUAL) s ON (r.NOMBRE=s.NOMBRE)
      WHEN NOT MATCHED THEN INSERT (NOMBRE, DESCRIPCION) VALUES ('OPERADOR','Operación diaria')`);

    const f = await conn.execute(`SELECT COUNT(*) CNT FROM FARMACIAS`);
    if (Number(f.rows[0].CNT) === 0) {
      await conn.execute(`INSERT INTO FARMACIAS (CODIGO,NOMBRE,DIRECCION,DEPARTAMENTO,TELEFONO) VALUES ('CENTRAL','Farmacia Central','Zona 1','Guatemala','2222-0000')`);
    }

    const adminUser = process.env.ADMIN_USER || 'admin';
    const adminPass = process.env.ADMIN_PASSWORD || 'Admin123!';
    const u = await conn.execute(`SELECT COUNT(*) CNT FROM USUARIOS WHERE USUARIO=:usuario`, { usuario: adminUser });
    if (Number(u.rows[0].CNT) === 0) {
      const hash = await bcrypt.hash(adminPass, 10);
      await conn.execute(`INSERT INTO USUARIOS (USUARIO,NOMBRE,EMAIL,PASSWORD_HASH,ROL_ID,FARMACIA_ID)
        SELECT :usuario,:nombre,:email,:hash,r.ID,f.ID FROM ROLES r CROSS JOIN FARMACIAS f
        WHERE r.NOMBRE='ADMINISTRADOR' AND f.CODIGO='CENTRAL'`,
        { usuario: adminUser, nombre: 'Administrador General', email: 'admin@farmacias.local', hash });
    }

    const meds = await conn.execute(`SELECT COUNT(*) CNT FROM MEDICAMENTOS`);
    if (Number(meds.rows[0].CNT) === 0) {
      await conn.execute(`INSERT INTO MEDICAMENTOS (CODIGO,NOMBRE,PRESENTACION,LABORATORIO,PRECIO) VALUES ('MED-001','Acetaminofén','500 mg / 20 tabletas','Genérico',18.50)`);
      await conn.execute(`INSERT INTO MEDICAMENTOS (CODIGO,NOMBRE,PRESENTACION,LABORATORIO,PRECIO) VALUES ('MED-002','Ibuprofeno','400 mg / 20 tabletas','Genérico',24.00)`);
      await conn.execute(`INSERT INTO INVENTARIO (FARMACIA_ID,MEDICAMENTO_ID,EXISTENCIA,STOCK_MINIMO,LOTE,FECHA_VENCIMIENTO)
        SELECT f.ID,m.ID,100,20,'LOTE-INICIAL',ADD_MONTHS(SYSDATE,18) FROM FARMACIAS f CROSS JOIN MEDICAMENTOS m WHERE f.CODIGO='CENTRAL'`);
    }
    await conn.commit();
  } finally { await conn.close(); }
}

