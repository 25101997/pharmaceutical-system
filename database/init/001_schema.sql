CREATE TABLE FARMACIA (
    ID_FARMACIA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(150) NOT NULL,
    DIRECCION VARCHAR2(250),
    DEPARTAMENTO VARCHAR2(100),
    ESTADO NUMBER(1) DEFAULT 1 NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE MEDICAMENTO (
    ID_MEDICAMENTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(50) NOT NULL UNIQUE,
    NOMBRE VARCHAR2(150) NOT NULL,
    DESCRIPCION VARCHAR2(500),
    PRECIO NUMBER(12,2) DEFAULT 0 NOT NULL,
    ESTADO NUMBER(1) DEFAULT 1 NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE INVENTARIO (
    ID_INVENTARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_FARMACIA NUMBER NOT NULL,
    ID_MEDICAMENTO NUMBER NOT NULL,
    EXISTENCIA NUMBER(12,2) DEFAULT 0 NOT NULL,
    STOCK_MINIMO NUMBER(12,2) DEFAULT 0 NOT NULL,
    CONSTRAINT FK_INV_FARMACIA FOREIGN KEY (ID_FARMACIA) REFERENCES FARMACIA(ID_FARMACIA),
    CONSTRAINT FK_INV_MEDICAMENTO FOREIGN KEY (ID_MEDICAMENTO) REFERENCES MEDICAMENTO(ID_MEDICAMENTO),
    CONSTRAINT UQ_INV_FARM_MED UNIQUE (ID_FARMACIA, ID_MEDICAMENTO)
);
